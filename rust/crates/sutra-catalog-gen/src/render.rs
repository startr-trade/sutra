//! Render the catalog pages and write them (or diff them, for `--check`).
//!
//! Pages share the house style of the frozen reference-baseline catalog: a
//! `<!-- GENERATED … -->` sentinel, the summary, an
//! item inventory, a `## Relationships` table with bidirectional links, `## Stability`, and a
//! preserved `<!-- MANUAL NOTES BELOW -->` tail.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use crate::model::{Crate, ItemKind, SourceFile, Workspace};
use crate::resolve::{crate_page, file_page, workspace_page, Graph};
use crate::util::{cell, rel_link};

/// Page header sentinel. The mixed-case "Generated by" is deliberate: a now-retired sibling
/// generator once shared this output root and swept away any `.md` whose head carried the
/// all-caps `GENERATED by` marker but that it had not emitted that run — the case difference is
/// what let the two coexist in one tree. Those pages are a frozen snapshot today.
const HEADER: &str = "<!-- Generated by rust/crates/sutra-catalog-gen (syn-backed Rust \
catalog). Re-run via `make catalog`. Do not edit above the MANUAL NOTES sentinel. -->";

const SENTINEL: &str = "<!-- MANUAL NOTES BELOW -->";

const NOTES_PLACEHOLDER: &str = "_Add hand-curated notes for this page here._";

const STABILITY: &str = "Pre-GA — internal Rust workspace crate. Not published (`publish = \
false`); the API surface is still evolving. Generated by `sutra-catalog-gen` — do not hand-edit \
above the MANUAL NOTES sentinel.";

/// A generated page: (catalog-output-relative path, content with default manual notes).
pub struct Page {
    pub path: String,
    pub content: String,
}

/// Render every catalog page for the workspace, in a deterministic order.
pub fn generate_pages(ws: &Workspace, g: &Graph) -> Vec<Page> {
    let ctx = Ctx::new(ws, g);
    let mut pages = Vec::new();

    pages.push(Page {
        path: workspace_page(),
        content: render_workspace(&ctx),
    });

    for c in &ws.crates {
        pages.push(Page {
            path: crate_page(c),
            content: render_crate(&ctx, c),
        });
        for f in &c.files {
            pages.push(Page {
                path: file_page(c, &f.rel),
                content: render_file(&ctx, c, f),
            });
        }
    }

    pages.sort_by(|a, b| a.path.cmp(&b.path));
    pages
}

/// Write all pages under `output`, preserving any existing manual notes. Returns the count.
pub fn write_all(output: &Path, pages: &[Page]) -> anyhow::Result<usize> {
    for p in pages {
        let target = output.join(&p.path);
        if let Some(parent) = target.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let final_content = preserve_manual_notes(&target, &p.content)?;
        // Write-if-changed keeps mtimes (and livereload) quiet.
        let unchanged = std::fs::read_to_string(&target)
            .map(|on_disk| on_disk == final_content)
            .unwrap_or(false);
        if !unchanged {
            std::fs::write(&target, final_content)?;
        }
    }
    Ok(pages.len())
}

/// Compare freshly-generated pages (already written into `generated_root`) against the committed
/// tree at `committed_root`. Returns the drifted page paths (empty = in sync).
pub fn diff_against(
    generated_root: &Path,
    committed_root: &Path,
    pages: &[Page],
) -> anyhow::Result<Vec<String>> {
    let mut drift = Vec::new();
    for p in pages {
        let gen_file = generated_root.join(&p.path);
        let committed_file = committed_root.join(&p.path);
        let gen_content = std::fs::read_to_string(&gen_file)?;
        if !committed_file.exists() {
            drift.push(format!("missing: {}", p.path));
            continue;
        }
        // Splice the committed file's manual notes into the generated content, exactly as a
        // real write would, so we compare the generated regions only.
        let expected = preserve_manual_notes(&committed_file, &gen_content)?;
        let actual = std::fs::read_to_string(&committed_file)?;
        if expected != actual {
            drift.push(format!("differs: {}", p.path));
        }
    }
    drift.sort();
    Ok(drift)
}

/// Splice the hand-written notes below `SENTINEL` from `target` (if it exists) into `generated`.
pub fn preserve_manual_notes(target: &Path, generated: &str) -> anyhow::Result<String> {
    let Some(gen_idx) = generated.find(SENTINEL) else {
        return Ok(generated.to_string());
    };
    let existing = match std::fs::read_to_string(target) {
        Ok(s) => s,
        Err(_) => return Ok(generated.to_string()),
    };
    let Some(exist_idx) = existing.find(SENTINEL) else {
        return Ok(generated.to_string());
    };
    let gen_tail = gen_idx + SENTINEL.len();
    let exist_tail = exist_idx + SENTINEL.len();
    Ok(format!(
        "{}{}",
        &generated[..gen_tail],
        &existing[exist_tail..]
    ))
}

