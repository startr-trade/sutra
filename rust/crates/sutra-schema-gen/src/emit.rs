#[allow(clippy::too_many_arguments)]
fn emit_decode_fn(
    cm: &ClassModel,
    element_plans: &[&FieldPlan],
    attribute_plans: &[&FieldPlan],
    value_plan: Option<&FieldPlan>,
    has_any: bool,
    is_choice: bool,
    pool: &mut FacetPool,
    out: &mut String,
) {
    let mutates_out = value_plan.is_some()
        || attribute_plans.iter().any(|p| !p.skip)
        || element_plans.iter().any(|p| !p.skip);

    w!(
        out,
        "pub fn decode_{}(node: &support::XmlNode, path: &str, ctx: &mut support::Ctx) -> {} {{\n",
        snake_case(&cm.name),
        cm.name
    );
    w!(
        out,
        "    let {}out = {}::default();\n",
        if mutates_out { "mut " } else { "" },
        cm.name
    );

    // Attributes.
    if attribute_plans.is_empty() {
        out.push_str("    support::check_attributes(node, &[], path, ctx);\n");
    } else {
        out.push_str("    const ATTRS: &[support::AttrSpec] = &[\n");
        for p in attribute_plans {
            w!(
                out,
                "        support::AttrSpec {{ name: \"{}\", required: {} }},\n",
                escape_rust(&p.fm.xml_name),
                p.fm.required
            );
        }
        out.push_str("    ];\n");
        out.push_str("    support::check_attributes(node, ATTRS, path, ctx);\n");
        for p in attribute_plans {
            if p.skip {
                continue;
            }
            w!(
                out,
                "    out.{} = support::decode_attr_string(node, \"{}\", path, {}, ctx);\n",
                p.rust_name,
                escape_rust(&p.fm.xml_name),
                pool.str_ref(&p.fm.facets)
            );
        }
    }

    // Element content model.
    if has_any {
        out.push_str("    // xs:any content — accepted without structural checks (wildcard).\n");
    } else if element_plans.is_empty() {
        out.push_str("    support::check_structure(node, &[], false, path, ctx);\n");
    } else {
        out.push_str("    const ELEMS: &[support::ElemSpec] = &[\n");
        for p in element_plans {
            w!(
                out,
                "        support::ElemSpec {{ name: \"{}\", required: {}, repeated: {} }},\n",
                escape_rust(&p.fm.xml_name),
                p.fm.required,
                p.fm.is_list
            );
        }
        out.push_str("    ];\n");
        if is_choice {
            out.push_str("    support::check_choice(node, ELEMS, path, ctx);\n");
        } else {
            out.push_str("    support::check_structure(node, ELEMS, false, path, ctx);\n");
        }
    }

    // simpleContent value.
    if let Some(vp) = value_plan {
        if !vp.skip {
            w!(
                out,
                "    out.{} = {};\n",
                vp.rust_name,
                decode_call_expr(vp, "node", "path", pool)
            );
        }
    }

    // Child element dispatch.
    let decoded: Vec<&&FieldPlan> = element_plans.iter().filter(|p| !p.skip).collect();
    if decoded.len() == 1 {
        let p = decoded[0];
        out.push_str("    for child in &node.children {\n");
        if p.fm.is_list {
            w!(
                out,
                "        if child.name == \"{}\" {{\n",
                escape_rust(&p.fm.xml_name)
            );
            emit_list_decode_body(p, pool, out, "            ");
            out.push_str("        }\n");
        } else {
            w!(
                out,
                "        if child.name == \"{}\" && out.{}.is_none() {{\n",
                escape_rust(&p.fm.xml_name),
                p.rust_name
            );
            emit_single_decode_body(p, pool, out, "            ");
            out.push_str("        }\n");
        }
        out.push_str("    }\n");
    } else if decoded.len() > 1 {
        out.push_str("    for child in &node.children {\n");
        out.push_str("        match child.name.as_str() {\n");
        for p in &decoded {
            if p.fm.is_list {
                w!(
                    out,
                    "            \"{}\" => {{\n",
                    escape_rust(&p.fm.xml_name)
                );
                emit_list_decode_body(p, pool, out, "                ");
            } else {
                w!(
                    out,
                    "            \"{}\" if out.{}.is_none() => {{\n",
                    escape_rust(&p.fm.xml_name),
                    p.rust_name
                );
                emit_single_decode_body(p, pool, out, "                ");
            }
            out.push_str("            }\n");
        }
        out.push_str("            _ => {}\n");
        out.push_str("        }\n");
        out.push_str("    }\n");
    }

    out.push_str("    out\n");
    out.push_str("}\n\n");
}

fn emit_single_decode_body(p: &FieldPlan, pool: &mut FacetPool, out: &mut String, indent: &str) {
    let xml = escape_rust(&p.fm.xml_name);
    w!(
        out,
        "{indent}let p = support::child_path(path, \"{xml}\", None);\n"
    );
    if let Some(nested) = p.nested_type {
        w!(
            out,
            "{indent}out.{} = Some(Box::new(decode_{}(child, &p, ctx)));\n",
            p.rust_name,
            snake_case(nested)
        );
    } else {
        w!(
            out,
            "{indent}out.{} = {};\n",
            p.rust_name,
            decode_call_expr(p, "child", "&p", pool)
        );
    }
}

fn emit_list_decode_body(p: &FieldPlan, pool: &mut FacetPool, out: &mut String, indent: &str) {
    let xml = escape_rust(&p.fm.xml_name);
    w!(
        out,
        "{indent}let p = support::child_path(path, \"{xml}\", Some(out.{}.len()));\n",
        p.rust_name
    );
    if let Some(nested) = p.nested_type {
        w!(
            out,
            "{indent}let item = decode_{}(child, &p, ctx);\n",
            snake_case(nested)
        );
        w!(out, "{indent}out.{}.push(item);\n", p.rust_name);
    } else {
        w!(
            out,
            "{indent}if let Some(v) = {} {{\n",
            decode_call_expr(p, "child", "&p", pool)
        );
        w!(out, "{indent}    out.{}.push(v);\n", p.rust_name);
        w!(out, "{indent}}}\n");
    }
}

/// The scalar/enum decode call for a plan (an `Option<T>` expression).
fn decode_call_expr(p: &FieldPlan, node_var: &str, path_var: &str, pool: &mut FacetPool) -> String {
    if let Some(enum_type) = p.enum_type {
        return format!("support::decode_enum({node_var}, {path_var}, {enum_type}::from_xml, ctx)");
    }
    let f = &p.fm.facets;
    match p.scalar.unwrap() {
        Scalar::Boolean => format!("support::decode_boolean({node_var}, {path_var}, ctx)"),
        Scalar::Int => {
            format!(
                "support::decode_int({node_var}, {path_var}, {}, ctx)",
                pool.num_ref(f)
            )
        }
        Scalar::Decimal => {
            format!(
                "support::decode_decimal({node_var}, {path_var}, {}, ctx)",
                pool.num_ref(f)
            )
        }
        Scalar::BigInt => {
            format!(
                "support::decode_integer({node_var}, {path_var}, {}, ctx)",
                pool.num_ref(f)
            )
        }
        Scalar::DateTime => {
            format!(
                "support::decode_datetime({node_var}, {path_var}, {}, ctx)",
                pool.str_ref(f)
            )
        }
        Scalar::Duration => format!("support::decode_duration({node_var}, {path_var}, ctx)"),
        Scalar::Bytes => {
            format!(
                "support::decode_base64({node_var}, {path_var}, {}, ctx)",
                pool.str_ref(f)
            )
        }
        // Text, QName
        _ => format!(
            "support::decode_string({node_var}, {path_var}, {}, ctx)",
            pool.str_ref(f)
        ),
    }
}

