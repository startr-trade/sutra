/// Deduplicates facet sets into module-level `static` constants (`F_S…` string facets,
/// `F_N…` numeric facets), numbered by first-encounter order.
struct FacetPool {
    str_names: Vec<String>,
    str_by_key: std::collections::HashMap<String, String>,
    num_names: Vec<String>,
    num_by_key: std::collections::HashMap<String, String>,
    by_name: std::collections::HashMap<String, crate::model::Facets>,
}

impl FacetPool {
    fn new() -> FacetPool {
        FacetPool {
            str_names: Vec::new(),
            str_by_key: std::collections::HashMap::new(),
            num_names: Vec::new(),
            num_by_key: std::collections::HashMap::new(),
            by_name: std::collections::HashMap::new(),
        }
    }

    fn str_ref(&mut self, f: &crate::model::Facets) -> String {
        if !has_str_facets(f) {
            return "&support::NO_STR_FACETS".to_string();
        }
        let key = str_key(f);
        if let Some(name) = self.str_by_key.get(&key) {
            return format!("&{name}");
        }
        let name = format!("F_S{}", self.str_by_key.len());
        self.str_by_key.insert(key, name.clone());
        self.str_names.push(name.clone());
        self.by_name
            .entry(name.clone())
            .or_insert_with(|| f.clone());
        format!("&{name}")
    }

    fn num_ref(&mut self, f: &crate::model::Facets) -> String {
        if !has_num_facets(f) {
            return "&support::NO_NUM_FACETS".to_string();
        }
        let key = num_key(f);
        if let Some(name) = self.num_by_key.get(&key) {
            return format!("&{name}");
        }
        let name = format!("F_N{}", self.num_by_key.len());
        self.num_by_key.insert(key, name.clone());
        self.num_names.push(name.clone());
        self.by_name
            .entry(name.clone())
            .or_insert_with(|| f.clone());
        format!("&{name}")
    }

    fn emit(&self, out: &mut String) {
        for name in &self.str_names {
            let f = &self.by_name[name];
            w!(
                out,
                "static {name}: support::StrFacets = support::StrFacets {{ min_len: {}, max_len: {}, patterns: {} }};\n",
                opt_u32(eff_min(f)),
                opt_u32(eff_max(f)),
                patterns_expr(f)
            );
        }
        for name in &self.num_names {
            let f = &self.by_name[name];
            w!(
                out,
                "static {name}: support::NumFacets = support::NumFacets {{ min_inclusive: {}, max_inclusive: {}, min_exclusive: {}, max_exclusive: {}, total_digits: {}, fraction_digits: {}, patterns: {} }};\n",
                opt_str(f.min_inclusive.as_deref()),
                opt_str(f.max_inclusive.as_deref()),
                opt_str(f.min_exclusive.as_deref()),
                opt_str(f.max_exclusive.as_deref()),
                opt_u32(f.total_digits),
                opt_u32(f.fraction_digits),
                patterns_expr(f)
            );
        }
        if !self.str_names.is_empty() || !self.num_names.is_empty() {
            out.push('\n');
        }
    }
}

fn has_str_facets(f: &crate::model::Facets) -> bool {
    f.min_length.is_some() || f.max_length.is_some() || f.length.is_some() || !f.patterns.is_empty()
}

fn has_num_facets(f: &crate::model::Facets) -> bool {
    f.min_inclusive.is_some()
        || f.max_inclusive.is_some()
        || f.min_exclusive.is_some()
        || f.max_exclusive.is_some()
        || f.total_digits.is_some()
        || f.fraction_digits.is_some()
        || !f.patterns.is_empty()
}

fn eff_min(f: &crate::model::Facets) -> Option<i64> {
    f.length.or(f.min_length)
}

fn eff_max(f: &crate::model::Facets) -> Option<i64> {
    f.length.or(f.max_length)
}

fn opt_i64_key(v: Option<i64>) -> String {
    match v {
        Some(n) => n.to_string(),
        None => "null".to_string(),
    }
}

fn opt_str_key(v: Option<&str>) -> String {
    match v {
        Some(s) => s.to_string(),
        None => "null".to_string(),
    }
}

fn str_key(f: &crate::model::Facets) -> String {
    format!(
        "S|{}|{}|{}",
        opt_i64_key(eff_min(f)),
        opt_i64_key(eff_max(f)),
        f.patterns.concat()
    )
}

fn num_key(f: &crate::model::Facets) -> String {
    format!(
        "N|{}|{}|{}|{}|{}|{}|{}",
        opt_str_key(f.min_inclusive.as_deref()),
        opt_str_key(f.max_inclusive.as_deref()),
        opt_str_key(f.min_exclusive.as_deref()),
        opt_str_key(f.max_exclusive.as_deref()),
        opt_i64_key(f.total_digits),
        opt_i64_key(f.fraction_digits),
        f.patterns.concat()
    )
}

fn opt_u32(v: Option<i64>) -> String {
    match v {
        Some(n) => format!("Some({n})"),
        None => "None".to_string(),
    }
}

fn opt_str(v: Option<&str>) -> String {
    match v {
        Some(s) => format!("Some(\"{}\")", escape_rust(s)),
        None => "None".to_string(),
    }
}

fn patterns_expr(f: &crate::model::Facets) -> String {
    if f.patterns.is_empty() {
        return "&[]".to_string();
    }
    let mut sb = String::from("&[");
    for (i, p) in f.patterns.iter().enumerate() {
        if i > 0 {
            sb.push_str(", ");
        }
        w!(sb, "\"{}\"", escape_rust(p));
    }
    sb.push(']');
    sb
}
