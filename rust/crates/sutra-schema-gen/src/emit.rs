fn emit_enum(em: &EnumModel, out: &mut String) {
    let mut used = HashSet::new();
    let variants: Vec<String> = em
        .values
        .iter()
        .map(|v| crate::names::sanitize_variant(&v.canonical_name, &mut used))
        .collect();

    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
    w!(out, "pub enum {} {{\n", em.name);
    for v in &variants {
        w!(out, "    {v},\n");
    }
    out.push_str("}\n\n");

    w!(out, "impl {} {{\n", em.name);
    out.push_str("    pub fn from_xml(value: &str) -> Option<Self> {\n");
    out.push_str("        match value {\n");
    for (i, v) in em.values.iter().enumerate() {
        w!(
            out,
            "            \"{}\" => Some(Self::{}),\n",
            escape_rust(&v.xml_value),
            variants[i]
        );
    }
    out.push_str("            _ => None,\n");
    out.push_str("        }\n");
    out.push_str("    }\n\n");
    out.push_str("    /// The canonical constant name — the contract's enum projection key.\n");
    out.push_str("    pub fn canonical_name(self) -> &'static str {\n");
    out.push_str("        match self {\n");
    for (i, v) in em.values.iter().enumerate() {
        w!(
            out,
            "            Self::{} => \"{}\",\n",
            variants[i],
            escape_rust(&v.canonical_name)
        );
    }
    out.push_str("        }\n");
    out.push_str("    }\n\n");
    out.push_str("    /// The XML enumeration value as written on the wire.\n");
    out.push_str("    pub fn xml_value(self) -> &'static str {\n");
    out.push_str("        match self {\n");
    for (i, v) in em.values.iter().enumerate() {
        w!(
            out,
            "            Self::{} => \"{}\",\n",
            variants[i],
            escape_rust(&v.xml_value)
        );
    }
    out.push_str("        }\n");
    out.push_str("    }\n");
    out.push_str("}\n\n");
}

// ---------------------------------------------------------------------------
// Class emission (struct + decode + map + shape row)
// ---------------------------------------------------------------------------

fn emit_class<'a>(
    cm: &'a ClassModel,
    class_names: &HashSet<&'a str>,
    enum_names: &HashSet<&'a str>,
    pool: &mut FacetPool,
    out: &mut String,
    shapes: &mut String,
) {
    let mut plans: Vec<FieldPlan<'a>> = Vec::new();
    let mut used_names: HashSet<String> = HashSet::new();
    let mut has_any = false;
    for fm in &cm.fields {
        if fm.is_any_element {
            has_any = true;
            continue;
        }
        if fm.is_mixed || fm.has_substitution_members {
            continue;
        }
        plans.push(plan_field(fm, class_names, enum_names, &mut used_names));
    }

    let is_choice = cm.xml_type_name.ends_with("Choice");

    let mut element_plans: Vec<&FieldPlan> = Vec::new();
    let mut attribute_plans: Vec<&FieldPlan> = Vec::new();
    let mut value_plan: Option<&FieldPlan> = None;
    for p in &plans {
        if p.fm.is_xml_value {
            value_plan = Some(p);
        } else if p.fm.is_attribute {
            attribute_plans.push(p);
        } else {
            element_plans.push(p);
        }
    }

    // ---- struct ----
    if let Some(doc) = &cm.javadoc {
        emit_doc_comment(out, doc, "");
    }
    out.push_str("#[derive(Debug, Clone, PartialEq, Default)]\n");
    w!(out, "pub struct {} {{\n", cm.name);
    for p in &plans {
        if p.skip {
            continue;
        }
        w!(out, "    pub {}: {},\n", p.rust_name, field_decl(p));
    }
    out.push_str("}\n\n");

    emit_decode_fn(
        cm,
        &element_plans,
        &attribute_plans,
        value_plan,
        has_any,
        is_choice,
        pool,
        out,
    );
    emit_map_fn(cm, &plans, out);
    emit_shape_row(cm, &plans, shapes);
}

fn field_decl(p: &FieldPlan) -> String {
    let base = if let Some(n) = p.nested_type {
        n.to_string()
    } else if let Some(e) = p.enum_type {
        e.to_string()
    } else {
        scalar_rust_type(p.scalar.unwrap()).to_string()
    };
    if p.fm.is_list {
        format!("Vec<{base}>")
    } else if p.nested_type.is_some() {
        format!("Option<Box<{base}>>")
    } else {
        format!("Option<{base}>")
    }
}

fn scalar_rust_type(kind: Scalar) -> &'static str {
    match kind {
        Scalar::Boolean => "bool",
        Scalar::Int => "i64",
        Scalar::Decimal | Scalar::BigInt => "bigdecimal::BigDecimal",
        Scalar::Bytes => "Vec<u8>",
        // Text, DateTime, Duration, QName
        _ => "String",
    }
}

