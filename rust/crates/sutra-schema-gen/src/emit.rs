// Map projection function
// ---------------------------------------------------------------------------

fn emit_map_fn(cm: &ClassModel, plans: &[FieldPlan], out: &mut String) {
    let projected: Vec<&FieldPlan> = plans.iter().filter(|p| !p.skip).collect();

    let param = if projected.is_empty() { "_v" } else { "v" };
    w!(
        out,
        "pub fn map_{}({param}: &{}) -> support::MapValue {{\n",
        snake_case(&cm.name),
        cm.name
    );
    if projected.is_empty() {
        out.push_str("    support::MapValue::Map(Vec::new())\n");
        out.push_str("}\n\n");
        return;
    }
    out.push_str("    let mut m: Vec<(String, support::MapValue)> = Vec::new();\n");
    for p in &projected {
        let key = escape_rust(&p.fm.xml_name);
        let map_key = if p.fm.is_xml_value {
            "value".to_string()
        } else {
            key
        };
        if p.fm.is_list {
            w!(
                out,
                "    support::push_group(&mut m, \"{}\", v.{}.iter().map({}).collect());\n",
                map_key,
                p.rust_name,
                list_item_mapper(p)
            );
        } else if let Some(nested) = p.nested_type {
            w!(out, "    if let Some(x) = &v.{} {{\n", p.rust_name);
            w!(
                out,
                "        m.push((\"{}\".to_string(), map_{}(x)));\n",
                map_key,
                snake_case(nested)
            );
            out.push_str("    }\n");
        } else if p.enum_type.is_some() {
            w!(out, "    if let Some(x) = v.{} {{\n", p.rust_name);
            w!(
                out,
                "        m.push((\"{}\".to_string(), support::MapValue::Str(x.canonical_name().to_string())));\n",
                map_key
            );
            out.push_str("    }\n");
        } else {
            match p.scalar.unwrap() {
                Scalar::Boolean => {
                    w!(out, "    if let Some(x) = v.{} {{\n", p.rust_name);
                    w!(
                        out,
                        "        m.push((\"{}\".to_string(), support::MapValue::Bool(x)));\n",
                        map_key
                    );
                    out.push_str("    }\n");
                }
                Scalar::Int => {
                    w!(out, "    if let Some(x) = v.{} {{\n", p.rust_name);
                    w!(
                        out,
                        "        m.push((\"{}\".to_string(), support::MapValue::Int(x)));\n",
                        map_key
                    );
                    out.push_str("    }\n");
                }
                Scalar::Decimal | Scalar::BigInt => {
                    w!(out, "    if let Some(x) = &v.{} {{\n", p.rust_name);
                    w!(out, "        m.push((\"{}\".to_string(), support::MapValue::Dec(x.clone())));\n", map_key);
                    out.push_str("    }\n");
                }
                Scalar::Bytes => {
                    w!(out, "    if let Some(x) = &v.{} {{\n", p.rust_name);
                    w!(out, "        m.push((\"{}\".to_string(), support::MapValue::Bytes(x.clone())));\n", map_key);
                    out.push_str("    }\n");
                }
                _ => {
                    w!(out, "    if let Some(x) = &v.{} {{\n", p.rust_name);
                    w!(out, "        m.push((\"{}\".to_string(), support::MapValue::Str(x.clone())));\n", map_key);
                    out.push_str("    }\n");
                }
            }
        }
    }
    out.push_str("    support::MapValue::Map(m)\n");
    out.push_str("}\n\n");
}

/// Closure / fn-path mapping one list item to a MapValue.
fn list_item_mapper(p: &FieldPlan) -> String {
    if let Some(nested) = p.nested_type {
        return format!("map_{}", snake_case(nested));
    }
    if p.enum_type.is_some() {
        return "|x| support::MapValue::Str(x.canonical_name().to_string())".to_string();
    }
    match p.scalar.unwrap() {
        Scalar::Boolean => "|x| support::MapValue::Bool(*x)".to_string(),
        Scalar::Int => "|x| support::MapValue::Int(*x)".to_string(),
        Scalar::Decimal | Scalar::BigInt => "|x| support::MapValue::Dec(x.clone())".to_string(),
        Scalar::Bytes => "|x| support::MapValue::Bytes(x.clone())".to_string(),
        _ => "|x| support::MapValue::Str(x.clone())".to_string(),
    }
}

// ---------------------------------------------------------------------------
// Shape metadata
// ---------------------------------------------------------------------------

fn emit_shape_row(cm: &ClassModel, plans: &[FieldPlan], shapes: &mut String) {
    w!(shapes, "    (\"{}\", &[\n", escape_rust(&cm.name));
    for p in plans {
        if p.skip {
            continue;
        }
        let name = if p.fm.is_xml_value {
            "value"
        } else {
            &p.fm.xml_name
        };
        let (kind, type_name) = if p.fm.is_list {
            (
                "List",
                p.nested_type
                    .map(str::to_string)
                    .unwrap_or_else(|| scalar_shape_name(p)),
            )
        } else if let Some(nested) = p.nested_type {
            ("Nested", nested.to_string())
        } else {
            ("Scalar", scalar_shape_name(p))
        };
        w!(
            shapes,
            "        support::FieldShape {{ name: \"{}\", kind: support::FieldKind::{}, type_name: \"{}\" }},\n",
            escape_rust(name),
            kind,
            escape_rust(&type_name)
        );
    }
    shapes.push_str("    ]),\n");
}

fn scalar_shape_name(p: &FieldPlan) -> String {
    if p.enum_type.is_some() {
        return "string".to_string();
    }
    match p.scalar.unwrap() {
        Scalar::Boolean => "boolean",
        Scalar::Int | Scalar::BigInt => "integer",
        Scalar::Decimal => "decimal",
        Scalar::DateTime => "datetime",
        Scalar::Bytes => "bytes",
        _ => "string",
    }
    .to_string()
}

// ---------------------------------------------------------------------------
// Field planning
// ---------------------------------------------------------------------------

fn plan_field<'a>(
    fm: &'a FieldModel,
    class_names: &HashSet<&'a str>,
    enum_names: &HashSet<&'a str>,
    used_names: &mut HashSet<String>,
) -> FieldPlan<'a> {
    let base = if fm.is_xml_value {
        "value"
    } else {
        fm.xml_name.as_str()
    };
    let mut name = snake_case(base);
    while used_names.contains(&name) {
        name = format!("{name}_2");
    }
    used_names.insert(name.clone());

    let mut plan = FieldPlan {
        fm,
        rust_name: name,
        scalar: None,
        enum_type: None,
        nested_type: None,
        skip: false,
    };

    match &fm.field_type {
        FieldType::Scalar(scalar) => plan.scalar = Some(*scalar),
        FieldType::Opaque => plan.skip = true,
        FieldType::Named(name) => {
            let name = name.as_str();
            if enum_names.contains(name) {
                plan.enum_type = enum_names.get(name).copied();
            } else if class_names.contains(name) {
                plan.nested_type = class_names.get(name).copied();
            } else {
                // Cross-schema or unresolvable reference — kept in the structural
                // specs (so its element is not "unexpected") but not decoded.
                plan.skip = true;
            }
        }
    }
    plan
}

fn emit_doc_comment(out: &mut String, text: &str, indent: &str) {
    for line in text.split('\n') {
        let line = line.trim_end_matches('\r').trim();
        w!(out, "{indent}/// {line}\n");
    }
}

