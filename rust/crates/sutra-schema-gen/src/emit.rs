/// The module-level `static` name for one schema's enum value table.
fn enum_static_name(enum_type: &str) -> String {
    format!("E_{enum_type}")
}

/// The `support::ScalarKind` variant for a neutral scalar (QName folds into `Text`,
/// matching the typed decoder's `decode_string` binding).
fn scalar_kind_variant(kind: Scalar) -> &'static str {
    match kind {
        Scalar::Boolean => "Boolean",
        Scalar::Int => "Int",
        Scalar::Decimal => "Decimal",
        Scalar::BigInt => "BigInt",
        Scalar::DateTime => "DateTime",
        Scalar::Duration => "Duration",
        Scalar::Bytes => "Bytes",
        // Text, QName
        _ => "Text",
    }
}

/// The `Content` expression and the `(str_facets, num_facets)` references for a field
/// plan — the slim analogue of `field_decl` + `decode_call_expr`.
fn field_content(p: &FieldPlan, pool: &mut FacetPool) -> (String, String, String) {
    let no_str = "&support::NO_STR_FACETS".to_string();
    let no_num = "&support::NO_NUM_FACETS".to_string();

    // Attributes: the typed decoder binds every attribute with `decode_attr_string`
    // (string + its str facets) regardless of declared type — match that.
    if p.fm.is_attribute {
        if p.skip {
            return ("support::Content::Skip".to_string(), no_str, no_num);
        }
        return (
            "support::Content::Scalar(support::ScalarKind::Text)".to_string(),
            pool.str_ref(&p.fm.facets),
            no_num,
        );
    }

    if p.skip {
        return ("support::Content::Skip".to_string(), no_str, no_num);
    }
    if let Some(enum_type) = p.enum_type {
        return (
            format!("support::Content::Enum({})", enum_static_name(enum_type)),
            no_str,
            no_num,
        );
    }
    if let Some(nested) = p.nested_type {
        return (
            format!("support::Content::Nested(\"{}\")", escape_rust(nested)),
            no_str,
            no_num,
        );
    }

    let scalar = p.scalar.expect("scalar plan carries a scalar kind");
    let content = format!(
        "support::Content::Scalar(support::ScalarKind::{})",
        scalar_kind_variant(scalar)
    );
    match scalar {
        // decode_string / decode_datetime / decode_base64 take the str facets.
        Scalar::Text | Scalar::QName | Scalar::DateTime | Scalar::Bytes => {
            (content, pool.str_ref(&p.fm.facets), no_num)
        }
        // decode_int / decode_decimal / decode_integer take the num facets.
        Scalar::Int | Scalar::Decimal | Scalar::BigInt => {
            (content, no_str, pool.num_ref(&p.fm.facets))
        }
        // decode_boolean / decode_duration are facet-free.
        Scalar::Boolean | Scalar::Duration => (content, no_str, no_num),
    }
}

/// Emit one `support::FieldDecl` row.
fn emit_field_decl(p: &FieldPlan, pool: &mut FacetPool, out: &mut String) {
    let slot = if p.fm.is_xml_value {
        "Value"
    } else if p.fm.is_attribute {
        "Attribute"
    } else {
        "Element"
    };
    let (content, str_ref, num_ref) = field_content(p, pool);
    w!(
        out,
        "            support::FieldDecl {{ xml: \"{}\", slot: support::Slot::{}, content: {}, required: {}, repeated: {}, str_facets: {}, num_facets: {} }},\n",
        escape_rust(&p.fm.xml_name),
        slot,
        content,
        p.fm.required,
        p.fm.is_list,
        str_ref,
        num_ref
    );
}

