//! The Rust-emitting backend: one self-contained module per schema (model, lenient
//! decoder, canonical map projection, shape metadata) plus the cross-schema `registry.rs`
//! and `lib.rs`. It reproduces the upstream emitter this backend was ported from
//! byte-for-byte after `cargo fmt`, with the generated body comments phrased against the
//! contracts; the enum accessor is `canonical_name()`.
//!
//! Content-model nuance: choice components (named `*Choice` by ISO 20022 design rule) get
//! an exactly-one-member `check_choice` instead of `check_structure`, avoiding false
//! missing-element violations.

use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;

use crate::model::{ClassModel, EnumModel, FieldModel, FieldType, ModuleInfo, ParseResult, Scalar};
use crate::names::{escape_rust, family, snake_case, variant_name};

macro_rules! w {
    ($dst:expr, $($arg:tt)*) => {{ let _ = write!($dst, $($arg)*); }};
}

pub const ISO_NS_PREFIX: &str = "urn:iso:std:iso:20022:tech:xsd:";

/// Generated-file header — contract-neutral, emitted verbatim.
const GEN_HEADER: &str = "// @generated by the sutra schema generator (XSD → Rust). DO NOT EDIT.\n";

/// Resolved plan for one field: how to declare, decode and project it.
struct FieldPlan<'a> {
    fm: &'a FieldModel,
    rust_name: String,
    scalar: Option<Scalar>,
    enum_type: Option<&'a str>,
    nested_type: Option<&'a str>,
    skip: bool,
}

/// The generation mode. **Slim** (default) emits the data-driven decode tables the
/// generic [`support::decode_document`] interpreter
/// walks — the form a generated binding crate normally commits. **Full** additionally emits the
/// typed message model (per-type structs + `decode_*` + `map_*`), opt-in via the CLI `--full`
/// flag for anyone who wants typed access.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Mode {
    /// Data-driven tables only (the default; the slim committed crate).
    #[default]
    Slim,
    /// The full typed model as well (opt-in, not committed).
    Full,
}

/// The generator: accumulates per-schema [`ModuleInfo`] across `generate` calls, then
/// emits the cross-schema `registry.rs` / `lib.rs`.
pub struct Generator {
    modules: Vec<ModuleInfo>,
    feature_gating: bool,
    mode: Mode,
}

impl Default for Generator {
    fn default() -> Self {
        Generator {
            modules: Vec::new(),
            feature_gating: true,
            mode: Mode::Slim,
        }
    }
}

impl Generator {
    /// A generator in the default (slim) mode.
    pub fn new() -> Generator {
        Generator::default()
    }

    /// A generator in the given mode.
    pub fn with_mode(mode: Mode) -> Generator {
        Generator {
            mode,
            ..Generator::default()
        }
    }

    pub fn modules(&self) -> &[ModuleInfo] {
        &self.modules
    }

    /// The `#[cfg(feature = "…")]` line for a module, or empty when gating is off.
    fn cfg_line(&self, module: &str, indent: &str) -> String {
        if self.feature_gating {
            format!("{indent}#[cfg(feature = \"{}\")]\n", family(module))
        } else {
            String::new()
        }
    }

    /// Generate one Rust module file's content for `result` under module `module`,
    /// in the generator's configured [`Mode`].
    pub fn generate(&mut self, result: &ParseResult, module: &str) -> String {
        match self.mode {
            Mode::Slim => self.generate_slim(result, module),
            Mode::Full => self.generate_full(result, module),
        }
    }

    /// Emit the full typed model for one schema — structs + `decode_*` + `map_*` +
    /// shape metadata (the `--full` opt-in; not the committed form).
    fn generate_full(&mut self, result: &ParseResult, module: &str) -> String {
        let namespace = result.target_namespace.clone().unwrap_or_default();
        let message_type = match namespace.strip_prefix(ISO_NS_PREFIX) {
            Some(slug) => slug.to_string(),
            None => module.to_string(),
        };

        let class_names: HashSet<&str> = result.classes.iter().map(|c| c.name.as_str()).collect();
        let enum_names: HashSet<&str> = result.enums.iter().map(|e| e.name.as_str()).collect();

        let mut pool = FacetPool::new();
        let mut body = String::new();
        let mut shapes = String::new();

        for em in &result.enums {
            emit_enum(em, &mut body);
        }

        let mut root_rust_type: Option<String> = None;
        for cm in &result.classes {
            if root_rust_type.is_none() && cm.root_element_name.is_some() {
                root_rust_type = Some(cm.name.clone());
            }
            emit_class(
                cm,
                &class_names,
                &enum_names,
                &mut pool,
                &mut body,
                &mut shapes,
            );
        }

        let mut out = String::new();
        out.push_str(GEN_HEADER);
        w!(
            out,
            "//! {message_type} — model, lenient decoder, map projection and shape metadata.\n"
        );
        out.push_str("#![allow(non_camel_case_types)]\n");
        out.push_str("#![allow(clippy::upper_case_acronyms)]\n\n");
        out.push_str("use crate::support;\n\n");
        w!(
            out,
            "pub const NAMESPACE: &str = \"{}\";\n",
            escape_rust(&namespace)
        );
        w!(
            out,
            "pub const MESSAGE_TYPE: &str = \"{}\";\n\n",
            escape_rust(&message_type)
        );

        if let Some(root) = &root_rust_type {
            let root_class = result
                .classes
                .iter()
                .find(|c| &c.name == root)
                .expect("root class present");
            let root_element = root_class
                .root_element_name
                .as_deref()
                .expect("root element name present");
            let root_path = format!("/{root_element}");
            out.push_str("/// Lenient full-document decode. Hard-fails only on well-formedness\n");
            out.push_str(
                "/// (the well-formedness gate); every schema problem is a collected violation.\n",
            );
            w!(
                out,
                "pub fn decode(xml: &[u8]) -> Result<({root}, Vec<support::Violation>), support::ParseError> {{\n"
            );
            out.push_str("    let parsed = support::parse_document(xml)?;\n");
            out.push_str("    let mut ctx = support::Ctx::new(xml);\n");
            w!(
                out,
                "    if parsed.root.name != \"{}\" {{\n",
                escape_rust(root_element)
            );
            out.push_str("        let found = parsed.root.name.clone();\n");
            w!(
                out,
                "        ctx.violate(parsed.root.pos, \"/\", format!(\"expected root element '{}', found '{{found}}'\"));\n",
                escape_rust(root_element)
            );
            out.push_str("    }\n");
            out.push_str("    if parsed.namespace != NAMESPACE {\n");
            out.push_str("        let found = parsed.namespace.clone();\n");
            w!(
                out,
                "        ctx.violate(parsed.root.pos, \"{}\", format!(\"expected namespace '{{NAMESPACE}}', found '{{found}}'\"));\n",
                escape_rust(&root_path)
            );
            out.push_str("    }\n");
            w!(
                out,
                "    let doc = decode_{}(&parsed.root, \"{}\", &mut ctx);\n",
                snake_case(root),
                escape_rust(&root_path)
            );
            out.push_str("    Ok((doc, ctx.violations))\n");
            out.push_str("}\n\n");
        }

        out.push_str(&body);
        pool.emit(&mut out);

        out.push_str("/// Shape metadata (the navigation-shape contract): complex type name →\n");
        out.push_str("/// field table for deploy-time template-path checking.\n");
        out.push_str("pub static SHAPES: &[(&str, &[support::FieldShape])] = &[\n");
        out.push_str(&shapes);
        out.push_str("];\n\n");
        out.push_str(
            "pub fn shape_of(type_name: &str) -> Option<&'static [support::FieldShape]> {\n",
        );
        out.push_str(
            "    SHAPES.iter().find(|(n, _)| *n == type_name).map(|(_, fields)| *fields)\n",
        );
        out.push_str("}\n");

        self.modules.push(ModuleInfo {
            module_name: module.to_string(),
            namespace,
            message_type,
            root_rust_type,
        });
        out
    }

    /// Emit `registry.rs` from the accumulated modules, in the configured [`Mode`].
    pub fn registry(&self) -> String {
        match self.mode {
            Mode::Slim => self.registry_slim(),
            Mode::Full => self.registry_full(),
        }
    }

    /// Emit the full (typed) `registry.rs`: the `AnyDocument` enum over the typed
    /// documents plus the per-namespace decode/map match arms.
    fn registry_full(&self) -> String {
        let sorted: BTreeMap<&str, &ModuleInfo> = self
            .modules
            .iter()
            .filter(|m| m.root_rust_type.is_some())
            .map(|m| (m.module_name.as_str(), m))
            .collect();

        let mut out = String::new();
        out.push_str(GEN_HEADER);
        out.push_str("//! Slug→decoder registry: dispatches a document-element namespace to the\n");
        out.push_str("//! generated decoder. An unknown slug is a detectable\n");
        out.push_str("//! [`DecodeError::UnknownNamespace`] — the contract's could-not-validate\n");
        out.push_str("//! (schema-not-found) soft error. A non-well-formed body is the hard\n");
        out.push_str("//! [`DecodeError::NotWellFormed`] (the well-formedness gate).\n\n");
        out.push_str(
            "use crate::support::{self, FieldShape, MapValue, ParseError, Violation};\n\n",
        );
        w!(
            out,
            "pub const ISO20022_NS_PREFIX: &str = \"{ISO_NS_PREFIX}\";\n\n"
        );

        out.push_str("#[derive(Debug, Clone, PartialEq)]\n");
        out.push_str("pub enum AnyDocument {\n");
        for m in sorted.values() {
            out.push_str(&self.cfg_line(&m.module_name, "    "));
            let root = m.root_rust_type.as_deref().unwrap();
            w!(
                out,
                "    {}(Box<crate::{}::{}>),\n",
                variant_name(&m.module_name),
                m.module_name,
                root
            );
        }
        out.push_str("}\n\n");

        out.push_str("#[derive(Debug, Clone, PartialEq)]\n");
        out.push_str("pub struct Decoded {\n");
        out.push_str("    pub message_type: String,\n");
        out.push_str("    pub namespace: String,\n");
        out.push_str("    pub document: AnyDocument,\n");
        out.push_str("    pub violations: Vec<Violation>,\n");
        out.push_str("}\n\n");

        out.push_str("#[derive(Debug, Clone, PartialEq)]\n");
        out.push_str("pub enum DecodeError {\n");
        out.push_str(
            "    /// The document-element namespace has no generated decoder — detectable so\n",
        );
        out.push_str("    /// the codec can emit a soft \"could-not-validate\" and keep the payload routable.\n");
        out.push_str("    UnknownNamespace { namespace: String },\n");
        out.push_str("    /// The body is not well-formed XML (hard error).\n");
        out.push_str("    NotWellFormed(ParseError),\n");
        out.push_str("}\n\n");

        out.push_str("/// Every message type with a generated decoder, sorted by module name.\n");
        out.push_str("#[allow(unused_mut, clippy::let_and_return)]\n");
        out.push_str("pub fn message_types() -> Vec<&'static str> {\n");
        out.push_str("    let mut v: Vec<&'static str> = Vec::new();\n");
        let mut by_family: BTreeMap<&str, Vec<&ModuleInfo>> = BTreeMap::new();
        for m in sorted.values() {
            by_family.entry(family(&m.module_name)).or_default().push(m);
        }
        for (fam, list) in &by_family {
            w!(out, "    #[cfg(feature = \"{fam}\")]\n");
            out.push_str("    v.extend_from_slice(&[\n");
            for m in list {
                w!(out, "        crate::{}::MESSAGE_TYPE,\n", m.module_name);
            }
            out.push_str("    ]);\n");
        }
        out.push_str("    v\n");
        out.push_str("}\n\n");

        out.push_str("pub fn is_known_namespace(namespace: &str) -> bool {\n");
        out.push_str("    message_type_of(namespace).is_some()\n");
        out.push_str("}\n\n");

        out.push_str("/// The message-type slug for a known namespace: the tail of the\n");
        out.push_str("/// registry URN, e.g. `<prefix>order.001.001.01` → `order.001.001.01`.\n");
        out.push_str("pub fn message_type_of(namespace: &str) -> Option<&'static str> {\n");
        out.push_str("    match namespace {\n");
        for m in sorted.values() {
            out.push_str(&self.cfg_line(&m.module_name, "        "));
            w!(
                out,
                "        crate::{0}::NAMESPACE => Some(crate::{0}::MESSAGE_TYPE),\n",
                m.module_name
            );
        }
        out.push_str("        _ => None,\n");
        out.push_str("    }\n");
        out.push_str("}\n\n");

        out.push_str("/// Decode by sniffing the document element's namespace.\n");
        out.push_str("pub fn decode(xml: &[u8]) -> Result<Decoded, DecodeError> {\n");
        out.push_str("    let (namespace, _root) = support::sniff_root(xml).map_err(DecodeError::NotWellFormed)?;\n");
        out.push_str("    decode_for_namespace(&namespace, xml)\n");
        out.push_str("}\n\n");

        out.push_str("/// Decode against the decoder registered for `namespace`.\n");
        out.push_str("pub fn decode_for_namespace(namespace: &str, xml: &[u8]) -> Result<Decoded, DecodeError> {\n");
        out.push_str("    match namespace {\n");
        for m in sorted.values() {
            let var = variant_name(&m.module_name);
            out.push_str(&self.cfg_line(&m.module_name, "        "));
            w!(out, "        crate::{}::NAMESPACE => {{\n", m.module_name);
            w!(
                out,
                "            let (doc, violations) = crate::{}::decode(xml).map_err(DecodeError::NotWellFormed)?;\n",
                m.module_name
            );
            out.push_str("            Ok(Decoded {\n");
            w!(
                out,
                "                message_type: crate::{}::MESSAGE_TYPE.to_string(),\n",
                m.module_name
            );
            out.push_str("                namespace: namespace.to_string(),\n");
            w!(
                out,
                "                document: AnyDocument::{var}(Box::new(doc)),\n"
            );
            out.push_str("                violations,\n");
            out.push_str("            })\n");
            out.push_str("        }\n");
        }
        out.push_str("        _ => Err(DecodeError::UnknownNamespace { namespace: namespace.to_string() }),\n");
        out.push_str("    }\n");
        out.push_str("}\n\n");

        out.push_str("impl Decoded {\n");
        out.push_str("    /// Full document projection (envelope included).\n");
        out.push_str("    pub fn document_map(&self) -> MapValue {\n");
        out.push_str("        match &self.document {\n");
        for m in sorted.values() {
            out.push_str(&self.cfg_line(&m.module_name, "            "));
            w!(
                out,
                "            AnyDocument::{}(d) => crate::{}::map_{}(d),\n",
                variant_name(&m.module_name),
                m.module_name,
                snake_case(m.root_rust_type.as_deref().unwrap())
            );
        }
        if self.feature_gating {
            out.push_str("            #[allow(unreachable_patterns)]\n");
            out.push_str("            _ => unreachable!(\"no message-family feature enabled\"),\n");
        }
        out.push_str("        }\n");
        out.push_str("    }\n\n");
        out.push_str("    /// Business-message projection — the contract's body-map view\n");
        out.push_str("    /// (the single-child `<Document>` envelope unwrapped).\n");
        out.push_str("    pub fn body_map(&self) -> MapValue {\n");
        out.push_str("        support::unwrap_envelope(self.document_map())\n");
        out.push_str("    }\n");
        out.push_str("}\n\n");

        out.push_str(
            "/// Shape lookup across message types (deploy-time template-path checking).\n",
        );
        out.push_str("pub fn shape_of(message_type: &str, type_name: &str) -> Option<&'static [FieldShape]> {\n");
        out.push_str("    match message_type {\n");
        for m in sorted.values() {
            out.push_str(&self.cfg_line(&m.module_name, "        "));
            w!(
                out,
                "        crate::{0}::MESSAGE_TYPE => crate::{0}::shape_of(type_name),\n",
                m.module_name
            );
        }
        out.push_str("        _ => None,\n");
        out.push_str("    }\n");
        out.push_str("}\n\n");

        out.push_str(
            "/// The root (document) type name for a message type, for `shape_of` entry.\n",
        );
        out.push_str("pub fn root_type_name(message_type: &str) -> Option<&'static str> {\n");
        out.push_str("    match message_type {\n");
        for m in sorted.values() {
            out.push_str(&self.cfg_line(&m.module_name, "        "));
            w!(
                out,
                "        crate::{}::MESSAGE_TYPE => Some(\"{}\"),\n",
                m.module_name,
                escape_rust(m.root_rust_type.as_deref().unwrap())
            );
        }
        out.push_str("        _ => None,\n");
        out.push_str("    }\n");
        out.push_str("}\n");

        out
    }

    /// Emit `lib.rs` from the accumulated modules.
    pub fn lib(&self) -> String {
        let mut out = String::new();
        out.push_str(GEN_HEADER);
        out.push_str(
            "//! Self-contained generated message model: lenient decoders, canonical-projection\n",
        );
        out.push_str("//! map projections, and shape metadata. External deps: quick-xml, regex, bigdecimal.\n\n");
        out.push_str("pub mod support;\n");
        out.push_str("pub mod registry;\n");
        let sorted: BTreeMap<&str, ()> = self
            .modules
            .iter()
            .map(|m| (m.module_name.as_str(), ()))
            .collect();
        for name in sorted.keys() {
            out.push_str(&self.cfg_line(name, ""));
            w!(out, "pub mod {name};\n");
        }
        out
    }

    // -----------------------------------------------------------------------
    // Slim emission (data-driven decode tables — the committed default)
    // -----------------------------------------------------------------------

    /// Emit the slim module for one schema: the `TypeDecl` decode tables (walked by
    /// [`support::decode_document`]), the referenced enum value tables, the pooled
    /// facet set, and the (unchanged) shape metadata. No typed structs, no per-type
    /// `decode_*` / `map_*` — the generic interpreter reproduces their behaviour.
    fn generate_slim(&mut self, result: &ParseResult, module: &str) -> String {
        let namespace = result.target_namespace.clone().unwrap_or_default();
        let message_type = match namespace.strip_prefix(ISO_NS_PREFIX) {
            Some(slug) => slug.to_string(),
            None => module.to_string(),
        };

        let class_names: HashSet<&str> = result.classes.iter().map(|c| c.name.as_str()).collect();
        let enum_names: HashSet<&str> = result.enums.iter().map(|e| e.name.as_str()).collect();

        // Plan every class (mirrors `emit_class`'s field planning) and record which
        // enums are referenced (first-encounter order) and the root type.
        let mut type_plans: Vec<(&ClassModel, Vec<FieldPlan>, bool, bool)> = Vec::new();
        let mut referenced_enums: Vec<&str> = Vec::new();
        let mut root_rust_type: Option<String> = None;
        for cm in &result.classes {
            if root_rust_type.is_none() && cm.root_element_name.is_some() {
                root_rust_type = Some(cm.name.clone());
            }
            let mut plans: Vec<FieldPlan> = Vec::new();
            let mut used_names: HashSet<String> = HashSet::new();
            let mut has_any = false;
            for fm in &cm.fields {
                if fm.is_any_element {
                    has_any = true;
                    continue;
                }
                if fm.is_mixed || fm.has_substitution_members {
                    continue;
                }
                let p = plan_field(fm, &class_names, &enum_names, &mut used_names);
                if let Some(e) = p.enum_type {
                    if !referenced_enums.contains(&e) {
                        referenced_enums.push(e);
                    }
                }
                plans.push(p);
            }
            let is_choice = cm.xml_type_name.ends_with("Choice");
            type_plans.push((cm, plans, has_any, is_choice));
        }

        // Build the TYPES body + shape rows (this populates the facet pool).
        let mut pool = FacetPool::new();
        let mut types_body = String::new();
        let mut shapes = String::new();
        for (cm, plans, has_any, is_choice) in &type_plans {
            w!(types_body, "    support::TypeDecl {{\n");
            w!(types_body, "        name: \"{}\",\n", escape_rust(&cm.name));
            w!(types_body, "        is_choice: {is_choice},\n");
            w!(types_body, "        has_any: {has_any},\n");
            w!(types_body, "        fields: &[\n");
            for p in plans {
                emit_field_decl(p, &mut pool, &mut types_body);
            }
            w!(types_body, "        ],\n");
            w!(types_body, "    }},\n");
            emit_shape_row(cm, plans, &mut shapes);
        }

        let mut out = String::new();
        out.push_str(GEN_HEADER);
        w!(
            out,
            "//! {message_type} — data-driven decode tables (slim) and shape metadata.\n"
        );
        out.push_str("#![allow(non_upper_case_globals)]\n\n");
        out.push_str("use crate::support;\n\n");
        w!(
            out,
            "pub const NAMESPACE: &str = \"{}\";\n",
            escape_rust(&namespace)
        );
        w!(
            out,
            "pub const MESSAGE_TYPE: &str = \"{}\";\n",
            escape_rust(&message_type)
        );
        if let Some(root) = &root_rust_type {
            let root_class = result
                .classes
                .iter()
                .find(|c| &c.name == root)
                .expect("root class present");
            let root_element = root_class
                .root_element_name
                .as_deref()
                .expect("root element name present");
            w!(
                out,
                "pub const ROOT_ELEMENT: &str = \"{}\";\n",
                escape_rust(root_element)
            );
            w!(
                out,
                "pub const ROOT_TYPE: &str = \"{}\";\n",
                escape_rust(root)
            );
        }
        out.push('\n');

        // Pooled facet constants.
        pool.emit(&mut out);

        // Referenced enum value tables (xml_value → canonical_name).
        for e in &referenced_enums {
            let em = result
                .enums
                .iter()
                .find(|x| x.name.as_str() == *e)
                .expect("referenced enum present");
            w!(
                out,
                "static {}: &[(&str, &str)] = &[\n",
                enum_static_name(e)
            );
            for v in &em.values {
                w!(
                    out,
                    "    (\"{}\", \"{}\"),\n",
                    escape_rust(&v.xml_value),
                    escape_rust(&v.canonical_name)
                );
            }
            out.push_str("];\n");
        }
        if !referenced_enums.is_empty() {
            out.push('\n');
        }

        // The decode tables (one row per line — `rustfmt::skip` keeps the dense form
        // instead of exploding each `FieldDecl` across nine lines).
        out.push_str("/// Complex-type decode tables — the data-driven decoder walks these.\n");
        out.push_str("#[rustfmt::skip]\n");
        out.push_str("pub static TYPES: &[support::TypeDecl] = &[\n");
        out.push_str(&types_body);
        out.push_str("];\n\n");

        // Shape metadata (unchanged surface).
        out.push_str("/// Shape metadata (the navigation-shape contract): complex type name →\n");
        out.push_str("/// field table for deploy-time template-path checking.\n");
        out.push_str("#[rustfmt::skip]\n");
        out.push_str("pub static SHAPES: &[(&str, &[support::FieldShape])] = &[\n");
        out.push_str(&shapes);
        out.push_str("];\n\n");
        out.push_str(
            "pub fn shape_of(type_name: &str) -> Option<&'static [support::FieldShape]> {\n",
        );
        out.push_str(
            "    SHAPES.iter().find(|(n, _)| *n == type_name).map(|(_, fields)| *fields)\n",
        );
        out.push_str("}\n");

        self.modules.push(ModuleInfo {
            module_name: module.to_string(),
            namespace,
            message_type,
            root_rust_type,
        });
        out
    }

    /// Emit the slim `registry.rs`: a per-namespace `Schema` table (decode tables +
    /// shape fn) dispatched to the generic [`support::decode_document`].
    fn registry_slim(&self) -> String {
        let sorted: BTreeMap<&str, &ModuleInfo> = self
            .modules
            .iter()
            .filter(|m| m.root_rust_type.is_some())
            .map(|m| (m.module_name.as_str(), m))
            .collect();

        let mut out = String::new();
        out.push_str(GEN_HEADER);
        out.push_str(
            "//! Namespace→schema registry (slim, data-driven): dispatches a document-element\n",
        );
        out.push_str("//! namespace to that schema's decode tables and runs the generic decoder\n");
        out.push_str("//! ([`support::decode_document`]). An unknown namespace is a detectable\n");
        out.push_str(
            "//! [`DecodeError::UnknownNamespace`] (the schema-not-found soft error); a\n",
        );
        out.push_str("//! non-well-formed body is the hard [`DecodeError::NotWellFormed`].\n\n");
        out.push_str(
            "use crate::support::{self, FieldShape, MapValue, ParseError, TypeDecl, Violation};\n\n",
        );
        w!(
            out,
            "pub const ISO20022_NS_PREFIX: &str = \"{ISO_NS_PREFIX}\";\n\n"
        );

        out.push_str("/// One schema's decode + shape tables, keyed by namespace.\n");
        out.push_str("struct Schema {\n");
        out.push_str("    namespace: &'static str,\n");
        out.push_str("    message_type: &'static str,\n");
        out.push_str("    root_element: &'static str,\n");
        out.push_str("    root_type: &'static str,\n");
        out.push_str("    types: &'static [TypeDecl],\n");
        out.push_str("    shape_of: fn(&str) -> Option<&'static [FieldShape]>,\n");
        out.push_str("}\n\n");

        out.push_str("static SCHEMAS: &[Schema] = &[\n");
        for m in sorted.values() {
            out.push_str(&self.cfg_line(&m.module_name, "    "));
            w!(
                out,
                "    Schema {{ namespace: crate::{0}::NAMESPACE, message_type: crate::{0}::MESSAGE_TYPE, root_element: crate::{0}::ROOT_ELEMENT, root_type: crate::{0}::ROOT_TYPE, types: crate::{0}::TYPES, shape_of: crate::{0}::shape_of }},\n",
                m.module_name
            );
        }
        out.push_str("];\n\n");

        out.push_str("fn schema_for(namespace: &str) -> Option<&'static Schema> {\n");
        out.push_str("    SCHEMAS.iter().find(|s| s.namespace == namespace)\n");
        out.push_str("}\n\n");

        out.push_str("#[derive(Debug, Clone, PartialEq)]\n");
        out.push_str("pub struct Decoded {\n");
        out.push_str("    pub message_type: String,\n");
        out.push_str("    pub namespace: String,\n");
        out.push_str("    document: MapValue,\n");
        out.push_str("    pub violations: Vec<Violation>,\n");
        out.push_str("}\n\n");

        out.push_str("impl Decoded {\n");
        out.push_str("    /// Full document projection (envelope included).\n");
        out.push_str("    pub fn document_map(&self) -> MapValue {\n");
        out.push_str("        self.document.clone()\n");
        out.push_str("    }\n\n");
        out.push_str(
            "    /// Business-message projection — the single-child `<Document>` envelope unwrapped.\n",
        );
        out.push_str("    pub fn body_map(&self) -> MapValue {\n");
        out.push_str("        support::unwrap_envelope(self.document.clone())\n");
        out.push_str("    }\n");
        out.push_str("}\n\n");

        out.push_str("#[derive(Debug, Clone, PartialEq)]\n");
        out.push_str("pub enum DecodeError {\n");
        out.push_str(
            "    /// The document-element namespace has no bundled schema — detectable so\n",
        );
        out.push_str("    /// the codec can emit a soft \"could-not-validate\" and keep the payload routable.\n");
        out.push_str("    UnknownNamespace { namespace: String },\n");
        out.push_str("    /// The body is not well-formed XML (hard error).\n");
        out.push_str("    NotWellFormed(ParseError),\n");
        out.push_str("}\n\n");

        out.push_str("/// Every message type with a bundled schema, sorted by module name.\n");
        out.push_str("pub fn message_types() -> Vec<&'static str> {\n");
        out.push_str("    SCHEMAS.iter().map(|s| s.message_type).collect()\n");
        out.push_str("}\n\n");

        out.push_str("pub fn is_known_namespace(namespace: &str) -> bool {\n");
        out.push_str("    schema_for(namespace).is_some()\n");
        out.push_str("}\n\n");

        out.push_str("/// The message-type slug for a known namespace: the tail of the\n");
        out.push_str("/// registry URN, e.g. `<prefix>order.001.001.01` → `order.001.001.01`.\n");
        out.push_str("pub fn message_type_of(namespace: &str) -> Option<&'static str> {\n");
        out.push_str("    schema_for(namespace).map(|s| s.message_type)\n");
        out.push_str("}\n\n");

        out.push_str("/// Decode by sniffing the document element's namespace.\n");
        out.push_str("pub fn decode(xml: &[u8]) -> Result<Decoded, DecodeError> {\n");
        out.push_str("    let (namespace, _root) = support::sniff_root(xml).map_err(DecodeError::NotWellFormed)?;\n");
        out.push_str("    decode_for_namespace(&namespace, xml)\n");
        out.push_str("}\n\n");

        out.push_str("/// Decode against the schema registered for `namespace`.\n");
        out.push_str("pub fn decode_for_namespace(namespace: &str, xml: &[u8]) -> Result<Decoded, DecodeError> {\n");
        out.push_str("    let schema = schema_for(namespace)\n");
        out.push_str("        .ok_or_else(|| DecodeError::UnknownNamespace { namespace: namespace.to_string() })?;\n");
        out.push_str("    let (document, violations) = support::decode_document(\n");
        out.push_str("        xml,\n");
        out.push_str("        schema.root_element,\n");
        out.push_str("        schema.namespace,\n");
        out.push_str("        schema.root_type,\n");
        out.push_str("        schema.types,\n");
        out.push_str("    )\n");
        out.push_str("    .map_err(DecodeError::NotWellFormed)?;\n");
        out.push_str("    Ok(Decoded {\n");
        out.push_str("        message_type: schema.message_type.to_string(),\n");
        out.push_str("        namespace: namespace.to_string(),\n");
        out.push_str("        document,\n");
        out.push_str("        violations,\n");
        out.push_str("    })\n");
        out.push_str("}\n\n");

        out.push_str(
            "/// Shape lookup across message types (deploy-time template-path checking).\n",
        );
        out.push_str("pub fn shape_of(message_type: &str, type_name: &str) -> Option<&'static [FieldShape]> {\n");
        out.push_str("    SCHEMAS\n");
        out.push_str("        .iter()\n");
        out.push_str("        .find(|s| s.message_type == message_type)\n");
        out.push_str("        .and_then(|s| (s.shape_of)(type_name))\n");
        out.push_str("}\n\n");

        out.push_str(
            "/// The root (document) type name for a message type, for `shape_of` entry.\n",
        );
        out.push_str("pub fn root_type_name(message_type: &str) -> Option<&'static str> {\n");
        out.push_str("    SCHEMAS\n");
        out.push_str("        .iter()\n");
        out.push_str("        .find(|s| s.message_type == message_type)\n");
        out.push_str("        .map(|s| s.root_type)\n");
        out.push_str("}\n");

        out
    }
}

